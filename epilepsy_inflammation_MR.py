"""## 4. 대립유전자 정렬 (Harmonization)

1. 결과의 효과 대립유전자를 노출과 같게 맞춤 (반대면 beta 부호 반전)
2. 상보 가닥(strand flip) 처리
3. **회문 SNP**(A/T, C/G): 빈도로 가닥을 판단할 수 없는 EAF 0.42~0.58은 제거, 나머지는 빈도로 정렬
4. 대립유전자가 맞지 않는 SNP 제거
"""

COMP = {"A": "T", "T": "A", "C": "G", "G": "C"}

def is_palindromic(a1, a2):
    return COMP.get(a1) == a2

def harmonise(exp_df, out_df):
    d = exp_df.merge(out_df, on="SNP", how="inner")
    rows = []
    for _, r in d.iterrows():
        ea, oa, eo, oo = r["effect_allele"], r["other_allele"], r["effect_allele_out"], r["other_allele_out"]
        b_out, f_out = r["beta_out"], r["eaf_out"]
        pal = is_palindromic(ea, oa)
        status = "ok"
        if pal:
            maf_e = min(r["eaf"], 1 - r["eaf"])
            if maf_e > PALINDROME_MAF_MAX:
                status = "drop_palindromic_ambiguous"
            else:
                # 빈도 방향으로 정렬
                same_dir = (r["eaf"] - 0.5) * (f_out - 0.5) > 0
                if (eo == ea) != same_dir:   # 가닥이 다른 것으로 판단
                    b_out, f_out = -b_out, 1 - f_out
        else:
            if (eo, oo) == (ea, oa):
                pass
            elif (eo, oo) == (oa, ea):
                b_out, f_out = -b_out, 1 - f_out
            elif (COMP.get(eo), COMP.get(oo)) == (ea, oa):
                pass
            elif (COMP.get(eo), COMP.get(oo)) == (oa, ea):
                b_out, f_out = -b_out, 1 - f_out
            else:
                status = "drop_allele_mismatch"
        rr = r.copy(); rr["beta_out"] = b_out; rr["eaf_out"] = f_out; rr["harmonise"] = status
        rows.append(rr)
    h = pd.DataFrame(rows)
    return h

