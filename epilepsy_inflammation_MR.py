def read_ilae(member, needed, zip_path=ILAE_ZIP, chunksize=1_000_000):
    keep = []
    with zipfile.ZipFile(zip_path) as zf:
        if member not in zf.namelist():
            raise FileNotFoundError(f"zip 안에 {member} 가 없습니다. 들어 있는 파일: {zf.namelist()}")
        # ILAE 파일은 헤더가 " \t "(공백+탭+공백)로, 데이터는 탭과 공백이 섞여 구분되어 있음
        # → 모든 공백 문자를 구분자로 사용 (sep=r"\s+"는 pandas의 빠른 C 엔진으로 처리됨)
        with zf.open(member) as fh:
            for chunk in pd.read_csv(fh, sep=r"\s+", chunksize=chunksize, dtype={"MarkerName": str}):
                chunk.columns = chunk.columns.str.strip()
                if "MarkerName" not in chunk.columns:
                    raise KeyError(f"MarkerName 열이 없습니다. 읽힌 열: {list(chunk.columns)}")
                keep.append(chunk[chunk["MarkerName"].isin(needed)])
    return pd.concat(keep, ignore_index=True)

