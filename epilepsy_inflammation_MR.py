"""## 5. MR 방법 구현

| 방법 | 가정 | 최소 SNP |
|---|---|---|
| Wald ratio | 단일 SNP | 1 |
| IVW (다중 랜덤효과) | 모든 도구변수가 유효 (또는 균형 잡힌 다면발현) | 2 |
| MR-Egger | 다면발현이 도구변수 강도와 독립 (InSIDE) | 3 |
| 가중 중앙값 | 가중치의 50% 이상이 유효 도구변수 | 3 |
| 가중 최빈값 | 가장 많은 도구변수 군집이 유효 | 3 |
"""

def wald_ratio(bx, by, sy):
    return by / bx, sy / np.abs(bx)

def ivw(bx, by, sy):
    w = 1 / sy**2
    beta = np.sum(w * bx * by) / np.sum(w * bx**2)
    se_fixed = np.sqrt(1 / np.sum(w * bx**2))
    k = len(bx)
    resid = by - beta * bx
    Q = np.sum(w * resid**2)
    phi = Q / (k - 1) if k > 1 else 1.0
    se = se_fixed * max(1.0, np.sqrt(phi))           # 다중 랜덤효과
    p = 2 * stats.norm.sf(abs(beta / se))
    Qp = stats.chi2.sf(Q, k - 1) if k > 1 else np.nan
    return dict(b=beta, se=se, p=p, Q=Q, Q_df=k - 1, Q_p=Qp)

def egger(bx, by, sy):
    s = np.sign(bx); s[s == 0] = 1
    bx, by = bx * s, by * s                          # 노출 효과를 양수로 정렬
    w = 1 / sy**2
    X = np.column_stack([np.ones_like(bx), bx])
    W = np.diag(w)
    XtWX_inv = np.linalg.inv(X.T @ W @ X)
    coef = XtWX_inv @ X.T @ W @ by
    resid = by - X @ coef
    k = len(bx)
    sigma = np.sqrt(np.sum(w * resid**2) / (k - 2))
    se = np.sqrt(np.diag(XtWX_inv)) * max(1.0, sigma)
    t = coef / se
    p = 2 * stats.t.sf(np.abs(t), k - 2)
    return dict(b=coef[1], se=se[1], p=p[1], intercept=coef[0], int_se=se[0], int_p=p[0])

def _wm(beta_iv, w):
    order = np.argsort(beta_iv)
    b, w = beta_iv[order], w[order] / w.sum()
    cum = np.cumsum(w) - 0.5 * w
    return np.interp(0.5, cum, b)

def weighted_median(bx, by, sy, sx, nboot=N_BOOT):
    b_iv, se_iv = by / bx, sy / np.abs(bx)
    w = 1 / se_iv**2
    est = _wm(b_iv, w)
    boots = []
    for _ in range(nboot):
        bx_b = rng.normal(bx, sx); by_b = rng.normal(by, sy)
        boots.append(_wm(by_b / bx_b, w))
    se = np.std(boots, ddof=1)
    return dict(b=est, se=se, p=2 * stats.norm.sf(abs(est / se)))

def _mode(b_iv, se_iv, phi=1.0):
    w = se_iv**-2; w = w / w.sum()
    s = 0.9 * min(np.std(b_iv, ddof=1), stats.median_abs_deviation(b_iv, scale="normal")) * len(b_iv) ** (-1 / 5)
    h = max(s * phi, 1e-8)
    grid = np.linspace(b_iv.min() - 3 * h, b_iv.max() + 3 * h, 2001)
    dens = (w[None, :] * stats.norm.pdf((grid[:, None] - b_iv[None, :]) / h)).sum(axis=1)
    return grid[np.argmax(dens)]

def weighted_mode(bx, by, sy, sx, nboot=N_BOOT):
    b_iv, se_iv = by / bx, sy / np.abs(bx)
    est = _mode(b_iv, se_iv)
    boots = []
    for _ in range(nboot):
        bx_b = rng.normal(bx, sx); by_b = rng.normal(by, sy)
        boots.append(_mode(by_b / bx_b, sy / np.abs(bx_b)))
    se = np.std(boots, ddof=1)
    return dict(b=est, se=se, p=2 * stats.norm.sf(abs(est / se)))

def steiger(h):
    # r² ≈ Z²/(Z²+N) 근사로 방향성 확인 (노출 r² > 결과 r² 이면 올바른 방향)
    n_exp = h["n"].astype(float) if "n" in h else pd.Series(34000.0, index=h.index)
    z_e = h["beta"] / h["se"]; z_o = h["beta_out"] / h["se_out"]
    r2_e = (z_e**2 / (z_e**2 + n_exp)).sum()
    r2_o = (z_o**2 / (z_o**2 + h["neff_out"])).sum()
    return r2_e, r2_o, r2_e > r2_o

"""## 6. MR 실행"""

def run_mr(h):
    bx, by = h["beta"].values, h["beta_out"].values
    sx, sy = h["se"].values, h["se_out"].values
    k = len(h)
    res = []
    if k == 1:
        b, se = wald_ratio(bx[0], by[0], sy[0])
        res.append(dict(method="Wald ratio", b=b, se=se, p=2 * stats.norm.sf(abs(b / se))))
        return res, {}
    iv = ivw(bx, by, sy)
    res.append(dict(method="IVW", b=iv["b"], se=iv["se"], p=iv["p"]))
    extra = dict(Q=iv["Q"], Q_df=iv["Q_df"], Q_p=iv["Q_p"])
    if k >= 3:
        eg = egger(bx, by, sy)
        res.append(dict(method="MR-Egger", b=eg["b"], se=eg["se"], p=eg["p"]))
        extra.update(egger_intercept=eg["intercept"], egger_int_p=eg["int_p"])
        res.append(dict(method="Weighted median", **weighted_median(bx, by, sy, sx)))
        res.append(dict(method="Weighted mode", **weighted_mode(bx, by, sy, sx)))
    return res, extra

all_res, all_sens = [], []
for out_name, h in harm.items():
    for prot, hp in h.groupby("protein"):
        res, extra = run_mr(hp)
        r2e, r2o, ok = steiger(hp)
        for r in res:
            all_res.append(dict(protein=prot, outcome=out_name, n_snp=len(hp), **r))
        all_sens.append(dict(protein=prot, outcome=out_name, n_snp=len(hp),
                             steiger_r2_exp=r2e, steiger_r2_out=r2o, steiger_correct=ok, **extra))

mr = pd.DataFrame(all_res)
